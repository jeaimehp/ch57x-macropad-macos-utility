import SwiftUI

/// Physical layout of the pad's top plate in millimetres, measured from a photo of the
/// user's pad next to a ruler (origin = top-left corner of the plate).
enum PadGeometry {
    static let plate = CGSize(width: 106, height: 61)
    static let plateCornerRadius: CGFloat = 5
    /// One window around all six keycaps. Keycap skirts overhang the switches by ~2 mm,
    /// so a window the size of the keycap block tolerates small measuring errors.
    static let keyWindow = CGRect(x: 7, y: 5, width: 66, height: 45.5)
    static let knobCenter = CGPoint(x: 97.4, y: 23.6)
    static let knobHoleDiameter: CGFloat = 22
    /// Column centres of the 3 key columns (keycap ≈19.7 mm, pitch ≈23.15 mm).
    static let columnCenters: [CGFloat] = [16.85, 40.0, 63.15]
}

/// Faceplate overlay: a pad-shaped card with the key window and knob hole cut out, top-row
/// labels printed above the window and bottom-row labels below it. Two copies per Letter page.
struct FaceplateSheetView: View {
    let mapping: PadMapping
    let title: String

    private func mm(_ v: CGFloat) -> CGFloat { LabelSheetView.mm(v) }
    private var controls: [PadControl] { PadControls.list(mapping) }

    var body: some View {
        VStack(alignment: .leading, spacing: 14) {
            HStack(alignment: .bottom) {
                VStack(alignment: .leading, spacing: 3) {
                    Text("MicroPad Faceplate — \(title)").font(.system(size: 17, weight: .bold))
                    Text("1 · Cut along the dashed outline.   2 · Cut out the key window and the knob circle.   3 · Lay it over the pad — keys and knob poke through.")
                        .font(.system(size: 8)).foregroundStyle(.gray)
                }
                Spacer()
                VStack(alignment: .trailing, spacing: 2) {
                    Rectangle().fill(Color.black).frame(width: mm(50), height: 3)
                    Text("Scale check: this bar = 50 mm").font(.system(size: 7))
                }
            }
            Text("A · One-piece faceplate").font(.system(size: 10, weight: .semibold))
            faceplate
            faceplate
            VStack(alignment: .leading, spacing: 1) {
                Text("B · Tape-on strips").font(.system(size: 10, weight: .semibold))
                Text("Cut out and tape the top strip above the keys and the bottom strip below them (two sets).")
                    .font(.system(size: 7)).foregroundStyle(.gray)
            }
            VStack(alignment: .leading, spacing: mm(5)) { stripSet; stripSet }
            Text("Sized for a ≈106 × 61 mm pad (measured from your photo): key window \(Int(PadGeometry.keyWindow.width)) × \(String(format: "%.1f", PadGeometry.keyWindow.height)) mm, knob hole \(Int(PadGeometry.knobHoleDiameter)) mm. The knob sits at the pad's edge, so its circle cuts a notch into the right side. If it doesn't line up, measure the outer edges of your six-key block and the knob position — the sizes live in PadGeometry and can be adjusted. The strips need no exact fit.")
                .font(.system(size: 7)).foregroundStyle(.gray)
                .fixedSize(horizontal: false, vertical: true)
            Spacer(minLength: 0)
            Text("Generated by MicroPad Studio · print at 100 % (Actual Size), not “Fit to page”.")
                .font(.system(size: 7)).foregroundStyle(.gray)
        }
        .padding(36)
        .frame(width: LabelSheetView.page.width, height: LabelSheetView.page.height, alignment: .topLeading)
        .background(Color.white)
        .foregroundStyle(.black)
        .environment(\.colorScheme, .light)
    }

    // MARK: - One overlay at true size

    private var faceplate: some View {
        let g = PadGeometry.self
        let cut = StrokeStyle(lineWidth: 0.6, dash: [3, 2])
        let w = g.keyWindow
        let knobR = g.knobHoleDiameter / 2
        return ZStack(alignment: .topLeading) {
            // Outline + knob hole (circle clipped to the plate so it reads as a notch).
            RoundedRectangle(cornerRadius: mm(g.plateCornerRadius)).strokeBorder(style: cut)
            Circle().stroke(style: cut)
                .frame(width: mm(g.knobHoleDiameter), height: mm(g.knobHoleDiameter))
                .offset(x: mm(g.knobCenter.x - knobR), y: mm(g.knobCenter.y - knobR))
                .frame(width: mm(g.plate.width), height: mm(g.plate.height), alignment: .topLeading)
                .clipShape(RoundedRectangle(cornerRadius: mm(g.plateCornerRadius)))
            // Key window, hatched lightly so it's obvious what to remove.
            RoundedRectangle(cornerRadius: mm(1)).fill(Color(white: 0.93))
                .overlay(RoundedRectangle(cornerRadius: mm(1)).strokeBorder(style: cut))
                .overlay(Text("cut out").font(.system(size: 7)).foregroundStyle(.gray))
                .frame(width: mm(w.width), height: mm(w.height))
                .offset(x: mm(w.minX), y: mm(w.minY))

            ForEach(controls) { c in label(for: c) }
        }
        .frame(width: mm(g.plate.width), height: mm(g.plate.height), alignment: .topLeading)
    }

    // MARK: - Tape-on strips (same label positions as the faceplate bands)

    private var stripSet: some View {
        VStack(alignment: .leading, spacing: mm(3)) {
            strip(height: PadGeometry.keyWindow.minY, top: true)
            strip(height: PadGeometry.plate.height - PadGeometry.keyWindow.maxY, top: false)
        }
    }

    private func strip(height: CGFloat, top: Bool) -> some View {
        let g = PadGeometry.self
        let knobX = g.keyWindow.maxX + 2, knobW = g.plate.width - knobX - 1
        let knob = controls.filter { if case .knob = $0.kind { return true } else { return false } }
        func knobLabel(_ part: String) -> PadControl? { knob.first { $0.id.hasSuffix("knob-\(part)") } }
        return ZStack(alignment: .topLeading) {
            Rectangle().strokeBorder(style: StrokeStyle(lineWidth: 0.6, dash: [3, 2]))
            ForEach(controls) { c in
                if case .button(let row, let col) = c.kind, row == (top ? 0 : 1), col < g.columnCenters.count {
                    Group {
                        if top {
                            text(c.label, size: 6, weight: .bold, lines: 1)
                        } else {
                            VStack(spacing: 0.5) {
                                text(c.label, size: 6.5, weight: .bold, lines: 2)
                                text(c.keys, size: 4.5, weight: .regular, lines: 1, mono: true)
                            }
                        }
                    }
                    .frame(width: mm(22), height: mm(height - 0.6))
                    .offset(x: mm(g.columnCenters[col] - 11), y: mm(0.3))
                }
            }
            VStack(spacing: 0.5) {
                if top {
                    if let cw = knobLabel("cw") { text("↻ \(cw.label)", size: 6, weight: .bold, lines: 1) }
                } else {
                    if let p = knobLabel("press") { text("● \(p.label)", size: 6, weight: .bold, lines: 1) }
                    if let ccw = knobLabel("ccw") { text("↺ \(ccw.label)", size: 6, weight: .bold, lines: 1) }
                }
            }
            .frame(width: mm(knobW), height: mm(height - 0.6))
            .offset(x: mm(knobX), y: mm(0.3))
        }
        .frame(width: mm(g.plate.width), height: mm(height), alignment: .topLeading)
    }

    @ViewBuilder
    private func label(for c: PadControl) -> some View {
        let g = PadGeometry.self
        let w = g.keyWindow
        switch c.kind {
        case .button(let row, let col) where col < g.columnCenters.count:
            let colW: CGFloat = 22
            let x = g.columnCenters[col] - colW / 2
            if row == 0 {
                // Top band: ~5 mm → one line.
                text(c.label, size: 6, weight: .bold, lines: 1)
                    .frame(width: mm(colW), height: mm(w.minY - 0.6))
                    .offset(x: mm(x), y: mm(0.3))
            } else {
                // Bottom band: ~10 mm → label + keys.
                VStack(spacing: 0.5) {
                    text(c.label, size: 6.5, weight: .bold, lines: 2)
                    text(c.keys, size: 4.5, weight: .regular, lines: 1, mono: true)
                }
                .frame(width: mm(colW), height: mm(g.plate.height - w.maxY - 1))
                .offset(x: mm(x), y: mm(w.maxY + 0.5))
            }
        case .knob(let part):
            let x = w.maxX + 2, width = g.plate.width - (w.maxX + 2) - 1
            let top = g.knobCenter.y - g.knobHoleDiameter / 2
            let bottom = g.knobCenter.y + g.knobHoleDiameter / 2
            let (y, h, symbol): (CGFloat, CGFloat, String) = {
                switch part {
                case "cw":    return (1, top - 1.5, "↻")
                case "press": return (bottom + 0.8, 8, "●")
                default:      return (bottom + 9, 8, "↺")
                }
            }()
            text("\(symbol) \(c.label)", size: 6, weight: .bold, lines: 2)
                .frame(width: mm(width), height: mm(h))
                .offset(x: mm(x), y: mm(y))
        default:
            EmptyView()
        }
    }

    private func text(_ s: String, size: CGFloat, weight: Font.Weight, lines: Int, mono: Bool = false) -> some View {
        Text(s)
            .font(.system(size: size, weight: weight, design: mono ? .monospaced : .default))
            .multilineTextAlignment(.center)
            .lineLimit(lines)
            .minimumScaleFactor(0.55)
    }
}
