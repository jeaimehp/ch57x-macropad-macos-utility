import SwiftUI

/// Printable US-Letter label sheet for one mapping, laid out in real millimetres
/// (1 pt = 1/72 in) so it prints true to size at 100 %:
///   • keycap stickers (cut out, stick on the keys) — two sets
///   • knob legend for the plate below the knob
///   • desk card mirroring the pad layout
///   • full reference table
struct LabelSheetView: View {
    let mapping: PadMapping
    let title: String

    /// Sticker edge. Measured from a photo of the pad: standard MX keycaps with a flat
    /// top of ≈12.7 mm, so 12 mm leaves a small margin.
    static let keycapMM: CGFloat = 12
    /// Free plate area below the knob (pad ≈105×60 mm, knob ≈20 mm Ø at the right edge).
    static let knobLegendMM = CGSize(width: 17, height: 20)
    static let page = CGSize(width: 612, height: 792)       // US Letter in points

    static func mm(_ v: CGFloat) -> CGFloat { v * 72 / 25.4 }
    private func mm(_ v: CGFloat) -> CGFloat { Self.mm(v) }

    private var controls: [PadControl] { PadControls.list(mapping) }
    private var buttons: [PadControl] {
        controls.filter { if case .button = $0.kind { return true } else { return false } }
    }
    private var knob: [PadControl] {
        controls.filter { if case .knob = $0.kind { return true } else { return false } }
    }
    private func color(_ c: PadControl) -> Color {
        if case .knob = c.kind { return Color(white: 0.35) }
        return PadDiagramView.palette[(c.number - 1) % PadDiagramView.palette.count]
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 14) {
            header
            HStack(alignment: .top, spacing: 24) {
                VStack(alignment: .leading, spacing: 8) {
                    section("1 · Keycap stickers", "12 mm — fits standard MX keycap tops. Cut along the dashed lines (two sets).")
                    HStack(spacing: mm(6)) { stickerSet; stickerSet }
                }
                VStack(alignment: .leading, spacing: 8) {
                    section("2 · Knob legend", "Stick on the plate below the knob (two copies).")
                    HStack(spacing: mm(4)) { knobLegend; knobLegend }
                }
            }
            VStack(alignment: .leading, spacing: 8) {
                section("3 · Desk card", "Cut out and keep beside the pad.")
                deskCard
            }
            section("4 · Reference", nil)
            reference
            Spacer(minLength: 0)
            Text("Generated by MicroPad Studio · print at 100 % (Actual Size), not “Fit to page”.")
                .font(.system(size: 7)).foregroundStyle(.gray)
        }
        .padding(36)
        .frame(width: Self.page.width, height: Self.page.height, alignment: .topLeading)
        .background(Color.white)
        .foregroundStyle(.black)
        .environment(\.colorScheme, .light)
    }

    // MARK: - Pieces

    private var header: some View {
        HStack(alignment: .bottom) {
            VStack(alignment: .leading, spacing: 3) {
                Text("MicroPad Labels — \(title)").font(.system(size: 17, weight: .bold))
                if let s = mapping.summary {
                    Text(s).font(.system(size: 8)).foregroundStyle(.gray).lineLimit(2)
                }
            }
            Spacer()
            VStack(alignment: .trailing, spacing: 2) {
                Rectangle().fill(Color.black).frame(width: mm(50), height: 3)
                Text("Scale check: this bar = 50 mm").font(.system(size: 7))
            }
        }
    }

    private func section(_ t: String, _ sub: String?) -> some View {
        VStack(alignment: .leading, spacing: 1) {
            Text(t).font(.system(size: 10, weight: .semibold))
            if let sub { Text(sub).font(.system(size: 7)).foregroundStyle(.gray) }
        }
    }

    private var stickerSet: some View {
        Grid(horizontalSpacing: mm(2), verticalSpacing: mm(2)) {
            ForEach(0..<mapping.rows, id: \.self) { r in
                GridRow {
                    ForEach(0..<mapping.columns, id: \.self) { c in
                        if let ctl = buttons.first(where: { $0.kind == .button(row: r, col: c) }) {
                            sticker(ctl)
                        }
                    }
                }
            }
        }
    }

    private func sticker(_ c: PadControl) -> some View {
        VStack(spacing: 1) {
            Spacer(minLength: 0)
            Text(c.label)
                .font(.system(size: 6.5, weight: .heavy))
                .multilineTextAlignment(.center)
                .lineLimit(3).minimumScaleFactor(0.6)
                .padding(.horizontal, 1.5)
            Text(c.keys)
                .font(.system(size: 4.5, weight: .semibold, design: .monospaced))
                .lineLimit(1).minimumScaleFactor(0.5)
                .padding(.horizontal, 1.5)
            Spacer(minLength: 0)
        }
        .foregroundStyle(.white)
        .shadow(color: .black.opacity(0.45), radius: 0.4)
        .frame(width: mm(Self.keycapMM), height: mm(Self.keycapMM))
        .background(LinearGradient(colors: [color(c), color(c).opacity(0.75)],
                                   startPoint: .topLeading, endPoint: .bottomTrailing))
        .overlay(Rectangle().strokeBorder(style: StrokeStyle(lineWidth: 0.5, dash: [2, 1.5])))
    }

    private var knobLegend: some View {
        VStack(alignment: .leading, spacing: mm(1.2)) {
            ForEach([2, 1, 0].filter { $0 < knob.count }, id: \.self) { i in
                let c = knob[i]
                let symbol = c.id.hasSuffix("ccw") ? "↺" : c.id.hasSuffix("cw") ? "↻" : "●"
                HStack(alignment: .top, spacing: 2) {
                    Text(symbol).font(.system(size: 6, weight: .bold))
                    Text(c.label).font(.system(size: 5.5, weight: .bold))
                        .lineLimit(2).minimumScaleFactor(0.6)
                }
            }
        }
        .foregroundStyle(.white)
        .padding(mm(1.2))
        .frame(width: mm(Self.knobLegendMM.width), height: mm(Self.knobLegendMM.height), alignment: .topLeading)
        .background(RoundedRectangle(cornerRadius: 3).fill(Color(white: 0.12)))
        .overlay(RoundedRectangle(cornerRadius: 3).strokeBorder(FaceplateSheetView.knobGlow, lineWidth: 1))
        .overlay(RoundedRectangle(cornerRadius: 3)
            .strokeBorder(style: StrokeStyle(lineWidth: 0.5, dash: [2, 1.5])))
    }

    private var deskCard: some View {
        let cell = mm(24)
        return HStack(spacing: mm(3)) {
            Grid(horizontalSpacing: mm(2), verticalSpacing: mm(2)) {
                ForEach(0..<mapping.rows, id: \.self) { r in
                    GridRow {
                        ForEach(0..<mapping.columns, id: \.self) { c in
                            if let ctl = buttons.first(where: { $0.kind == .button(row: r, col: c) }) {
                                VStack(alignment: .leading, spacing: 1) {
                                    Text("\(ctl.number)").font(.system(size: 6, weight: .bold))
                                        .foregroundStyle(.white)
                                        .frame(width: 10, height: 10)
                                        .background(Circle().fill(color(ctl)))
                                    Spacer(minLength: 0)
                                    Text(ctl.label).font(.system(size: 8, weight: .bold))
                                        .lineLimit(2).minimumScaleFactor(0.6)
                                    Text(ctl.keys).font(.system(size: 5.5, design: .monospaced))
                                        .lineLimit(1).minimumScaleFactor(0.5)
                                }
                                .padding(3)
                                .frame(width: cell, height: cell * 0.82, alignment: .topLeading)
                                .background(RoundedRectangle(cornerRadius: 4).fill(color(ctl).opacity(0.14)))
                                .overlay(RoundedRectangle(cornerRadius: 4).strokeBorder(color(ctl), lineWidth: 1))
                            }
                        }
                    }
                }
            }
            if knob.count == 3 {
                VStack(spacing: 4) {
                    knobLine(knob[2], "↻")
                    ZStack {
                        Circle().strokeBorder(Color.black, lineWidth: 1.2)
                        Text(knob[1].label).font(.system(size: 6.5, weight: .bold))
                            .multilineTextAlignment(.center).lineLimit(2).minimumScaleFactor(0.6)
                            .padding(4)
                    }
                    .frame(width: mm(15), height: mm(15))
                    knobLine(knob[0], "↺")
                }
                .frame(width: mm(26))
            }
        }
        .padding(mm(3))
        .overlay(RoundedRectangle(cornerRadius: 8)
            .strokeBorder(style: StrokeStyle(lineWidth: 0.6, dash: [3, 2])))
    }

    private func knobLine(_ c: PadControl, _ symbol: String) -> some View {
        VStack(spacing: 0) {
            Text("\(symbol) \(c.label)").font(.system(size: 7, weight: .bold)).lineLimit(1)
            Text(c.keys).font(.system(size: 5, design: .monospaced)).lineLimit(1)
        }
        .minimumScaleFactor(0.6)
    }

    private var reference: some View {
        Grid(alignment: .leadingFirstTextBaseline, horizontalSpacing: 8, verticalSpacing: 3) {
            ForEach(controls) { c in
                GridRow {
                    Text("\(c.number)").font(.system(size: 7, weight: .bold)).foregroundStyle(.white)
                        .frame(width: 11, height: 11).background(Circle().fill(color(c)))
                    Text(c.position).font(.system(size: 7.5))
                    Text(c.keys).font(.system(size: 7.5, design: .monospaced))
                    VStack(alignment: .leading, spacing: 0) {
                        Text(c.label).font(.system(size: 7.5, weight: .semibold))
                        if !c.detail.isEmpty {
                            Text(c.detail).font(.system(size: 6.5)).foregroundStyle(.gray)
                                .fixedSize(horizontal: false, vertical: true)
                        }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                }
            }
        }
    }
}

/// Renders `LabelSheetView` to a vector PDF.
enum LabelSheetPDF {
    enum Style { case stickers, faceplate }

    @MainActor
    static func write(mapping: PadMapping, title: String, style: Style = .stickers, to url: URL) throws {
        switch style {
        case .stickers:  try render(LabelSheetView(mapping: mapping, title: title), to: url)
        case .faceplate: try render(FaceplateSheetView(mapping: mapping, title: title), to: url)
        }
    }

    @MainActor
    private static func render<V: View>(_ view: V, to url: URL) throws {
        let renderer = ImageRenderer(content: view)
        renderer.proposedSize = ProposedViewSize(LabelSheetView.page)
        var ok = false
        renderer.render { size, draw in
            var box = CGRect(origin: .zero, size: LabelSheetView.page)
            guard let ctx = CGContext(url as CFURL, mediaBox: &box, nil) else { return }
            ctx.beginPDFPage(nil)
            draw(ctx)
            ctx.endPDFPage()
            ctx.closePDF()
            ok = true
        }
        if !ok { throw CocoaError(.fileWriteUnknown) }
    }
}
